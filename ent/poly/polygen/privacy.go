type privacyStub struct {
	Name    string
	Package string
	// Base is the start of its policy files' names: the file that declares the schema, so they sort next to it.
	Base string
}

// Every ent schema and TPH pattern gets generated policy files, and may not write its own Policy or Privacy, which
// would skip the stages its mixins' rules run in. A TPC pattern isn't a table; its rules reach its members'
// policies. Found from source, since the policy files are part of the package that has to compile before anything
// can run.
func scanPrivacy(dir string) ([]*privacyStub, error) {
	fset := token.NewFileSet()
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	methods := map[string]map[string]bool{}
	embeds := map[string]map[string]bool{}
	declared := map[string]string{}
	pkg := ""
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		pkg = f.Name.Name
		if ast.IsGenerated(f) || isPolicyFile(path) {
			continue
		}
		for _, d := range f.Decls {
			if gd, ok := d.(*ast.GenDecl); ok {
				for _, name := range embedded(gd, embeds) {
					declared[name] = path
				}
				continue
			}
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || len(fd.Recv.List) != 1 {
				continue
			}
			recv := fd.Recv.List[0].Type
			if star, ok := recv.(*ast.StarExpr); ok {
				recv = star.X
			}
			id, ok := recv.(*ast.Ident)
			if !ok {
				continue
			}
			if methods[id.Name] == nil {
				methods[id.Name] = map[string]bool{}
			}
			methods[id.Name][fd.Name.Name] = true
		}
	}
	var out []*privacyStub
	perFile := map[string]int{}
	for name, e := range embeds {
		if e["ent.Schema"] || e["poly.TPH"] {
			perFile[declared[name]]++
		}
	}
	for name, e := range embeds {
		if !e["ent.Schema"] && !e["poly.TPH"] {
			continue
		}
		base := strings.ToLower(name)
		if f := declared[name]; perFile[f] == 1 {
			base = strings.TrimSuffix(filepath.Base(f), ".go")
		}
		s := &privacyStub{Name: name, Package: pkg, Base: base}
		for _, m := range []string{"Policy", "Privacy"} {
			if methods[name][m] {
				return nil, fmt.Errorf(
					"%s declares %s; its own rules go in the manual sections of its policy files, %s and %s",
					name,
					m,
					s.file(0),
					s.file(1),
				)
			}
		}
		out = append(out, s)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func embedded(gd *ast.GenDecl, into map[string]map[string]bool) []string {
	var names []string
	for _, spec := range gd.Specs {
		ts, ok := spec.(*ast.TypeSpec)
		if !ok {
			continue
		}
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		names = append(names, ts.Name.Name)
		for _, fld := range st.Fields.List {
			sel, ok := fld.Type.(*ast.SelectorExpr)
			if !ok || len(fld.Names) != 0 {
				continue
			}
			if x, ok := sel.X.(*ast.Ident); ok {
				if into[ts.Name.Name] == nil {
					into[ts.Name.Name] = map[string]bool{}
				}
				into[ts.Name.Name][x.Name+"."+sel.Sel.Name] = true
			}
		}
	}
	return names
}

// A schema's read rules go in its privacy policy file and its write rules in its permission policy file.
type policyKind struct {
	suffix, method, stagesType, listType string
}

var policyKinds = [...]policyKind{
	{"_privacy_policy.go", "PrivacyPolicy", "Query", "QueryPolicy"},
	{"_permission_policy.go", "PermissionPolicy", "Mutation", "MutationPolicy"},
}

func (s *privacyStub) file(kind int) string { return s.Base + policyKinds[kind].suffix }

// The header isn't Go's "Code generated ... DO NOT EDIT." line: the manual sections are hand-written, so linters
// and formatters must still read the file.
const privacyHeader = "// Code generated by polygen from the schema's mixins, patterns and edges. Write the schema's own rules\n" +
	"// between a stage's manual markers; polygen keeps them and rewrites everything else.\n"

func isPolicyFile(path string) bool {
	if !strings.HasSuffix(path, policyKinds[0].suffix) && !strings.HasSuffix(path, policyKinds[1].suffix) {
		return false
	}
	src, err := os.ReadFile(path)
	return err == nil && bytes.HasPrefix(src, []byte(privacyHeader))
}

var stageFields = [...]string{"Bypass", "Deny", "Filter", "Allow"}

func manualStart(stage int) string { return "// MANUAL " + strings.ToUpper(stageFields[stage]) }

func manualEnd(stage int) string { return "// END " + strings.ToUpper(stageFields[stage]) }

// manualSections reads what the schema's author wrote between each stage's markers, keyed by its start marker.
func manualSections(src []byte) map[string][]string {
	out := map[string][]string{}
	key, end := "", ""
	for _, line := range strings.Split(string(src), "\n") {
		t := strings.TrimSpace(line)
		switch {
		case key == "" && strings.HasPrefix(t, "// MANUAL "):
			key, end = t, "// END "+strings.TrimPrefix(t, "// MANUAL ")
			out[key] = nil
		case key != "" && t == end:
			key = ""
		case key != "":
			out[key] = append(out[key], t)
		}
	}
	return out
}

func renderPolicyFile(path string, s *privacyStub, kind int, r privacystage.Rendered, old []byte) ([]byte, error) {
	k := policyKinds[kind]
	manual := manualSections(old)
	imps := map[string]string{
		"entgo.io/ent":         "ent",
		"entgo.io/ent/privacy": "privacy",
		"github.com/acdifran/go-tools/ent/privacystage": "privacystage",
	}
	names := map[string]bool{"ent": true, "privacy": true, "privacystage": true}
	for p, n := range r.Imports {
		imps[p] = n
		names[n] = true
	}
	if old != nil {
		if f, err := parser.ParseFile(token.NewFileSet(), path, old, parser.ImportsOnly); err == nil {
			for _, spec := range f.Imports {
				p := strings.Trim(spec.Path.Value, `"`)
				n := filepath.Base(p)
				if spec.Name != nil {
					n = spec.Name.Name
				}
				if _, ok := imps[p]; !ok && !names[n] {
					imps[p] = n
				}
			}
		}
	}
	paths := make([]string, 0, len(imps))
	for p := range imps {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString(privacyHeader + "\npackage " + s.Package + "\n\nimport (\n")
	for _, p := range paths {
		if n := imps[p]; n != filepath.Base(p) {
			fmt.Fprintf(&b, "\t%s %q\n", n, p)
		} else {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
	}
	b.WriteString(")\n\n")
	if kind == 0 {
		b.WriteString("// Policy runs every bypass rule, then every deny, filter and allow rule, then denies anything no rule\n")
		b.WriteString("// allowed.\n")
		fmt.Fprintf(&b, "func (s %s) Policy() ent.Policy {\n", s.Name)
		fmt.Fprintf(&b, "\treturn privacystage.Build(s.%s(), s.%s())\n}\n\n", policyKinds[0].method, policyKinds[1].method)
	}
	fmt.Fprintf(&b, "func (%s) %s() privacystage.%s {\n\treturn privacystage.%s{\n", s.Name, k.method, k.stagesType, k.stagesType)
	for st, field := range stageFields {
		fmt.Fprintf(&b, "%s: privacy.%s{\n", field, k.listType)
		for _, rule := range r.Stages[st][kind] {
			fmt.Fprintf(&b, "%s, // %s\n", rule.Expr, rule.Source)
		}
		b.WriteString(manualStart(st) + "\n")
		for _, line := range manual[manualStart(st)] {
			b.WriteString(line + "\n")
		}
		b.WriteString(manualEnd(st) + "\n},\n")
	}
	b.WriteString("}\n}\n")
	src, err := imports.Process(path, []byte(b.String()), nil)
	if err != nil {
		return nil, fmt.Errorf("formatting %s: %w\n%s", path, err, b.String())
	}
	return src, nil
}

// writePrivacyFiles writes each schema's policy files and returns a function that puts the old files back. With no
// rendered rules it writes only the manual sections: a file can call a mixin rule that no longer exists, and the
// package has to compile for the loader to render the new ones.
func writePrivacyFiles(dir string, stubs []*privacyStub, rendered map[string]privacystage.Rendered) (func(), error) {
	originals := map[string][]byte{}
	restore := func() {
		for path, src := range originals {
			if src == nil {
				_ = os.Remove(path)
			} else {
				_ = os.WriteFile(path, src, 0o644)
			}
		}
	}
	byOwner, err := policyFilesByOwner(dir)
	if err != nil {
		return nil, err
	}
	keep := map[string]bool{}
	for _, s := range stubs {
		for kind := range policyKinds {
			path := filepath.Join(dir, s.file(kind))
			keep[path] = true
			orig, err := os.ReadFile(path)
			if err != nil && !os.IsNotExist(err) {
				restore()
				return nil, err
			}
			if _, saved := originals[path]; !saved {
				originals[path] = orig
			}
			old := orig
			if !bytes.HasPrefix(old, []byte(privacyHeader)) {
				old = byOwner[policyOwner{s.Name, policyKinds[kind].method}]
			}
			src, err := renderPolicyFile(path, s, kind, rendered[s.Name], old)
			if err != nil {
				restore()
				return nil, err
			}
			if bytes.Equal(orig, src) {
				continue
			}
			if err := os.WriteFile(path, src, 0o644); err != nil {
				restore()
				return nil, err
			}
		}
	}
	return restore, removeStale(dir, keep)
}

type policyOwner struct{ schema, method string }

var policyMethodRe = regexp.MustCompile(`func \((\w+)\) (PrivacyPolicy|PermissionPolicy)\(\)`)

// policyFilesByOwner finds each schema's existing policy files by what they declare, not their name, so a file
// renamed by a change to the naming keeps its manual sections.
func policyFilesByOwner(dir string) (map[policyOwner][]byte, error) {
	out := map[policyOwner][]byte{}
	for _, k := range policyKinds {
		paths, err := filepath.Glob(filepath.Join(dir, "*"+k.suffix))
		if err != nil {
			return nil, err
		}
		for _, p := range paths {
			src, err := os.ReadFile(p)
			if err != nil {
				return nil, err
			}
			if !bytes.HasPrefix(src, []byte(privacyHeader)) {
				continue
			}
			if m := policyMethodRe.FindSubmatch(src); m != nil {
				out[policyOwner{string(m[1]), string(m[2])}] = src
			}
		}
	}
	return out, nil
}

// removeStale deletes the policy files polygen wrote for schemas that are gone. The name is plain enough that a
// hand-written file can match, so only a file with polygen's header goes.
func removeStale(dir string, keep map[string]bool) error {
	var paths []string
	for _, k := range policyKinds {
		matches, err := filepath.Glob(filepath.Join(dir, "*"+k.suffix))
		if err != nil {
			return err
		}
		paths = append(paths, matches...)
	}
	for _, f := range paths {
		if !keep[f] && isPolicyFile(f) {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
