const tphFile = "poly_tph.go"

type exported struct {
	kind token.Token
	name string
}

func exportedDecls(dir string) ([]exported, error) {
	fset := token.NewFileSet()
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var out []exported
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") || strings.HasPrefix(filepath.Base(path), "poly_") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.IsExported() && d.Type.TypeParams == nil {
					out = append(out, exported{token.FUNC, d.Name.Name})
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if s.Name.IsExported() && s.TypeParams == nil {
							out = append(out, exported{token.TYPE, s.Name.Name})
						}
					case *ast.ValueSpec:
						// A var with no value is assigned by ent's runtime package after init, so a copy would
						// stay nil.
						if d.Tok == token.VAR && len(s.Values) == 0 {
							continue
						}
						for _, n := range s.Names {
							if n.IsExported() {
								out = append(out, exported{d.Tok, n.Name})
							}
						}
					}
				}
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, nil
}

func reexport(b *strings.Builder, pkg, from, to string, kind token.Token) {
	keyword := "var"
	if kind == token.TYPE || kind == token.CONST {
		keyword = kind.String()
	}
	fmt.Fprintf(b, "%s %s = %s.%s\n", keyword, to, pkg, from)
}

func writeGo(path string, src []byte) error {
	out, err := imports.Process(path, src, nil)
	if err != nil {
		_ = os.WriteFile(path+".broken", src, 0o644)
		return fmt.Errorf("formatting %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, out, 0o644)
}

// Ent's own package for the pattern's old type would still be there, and no longer compiles.
func removeEntFiles(dir string) error {
	paths, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, path := range paths {
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(b, []byte("// Code generated by ent, DO NOT EDIT.")) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

func writeTPH(g *gen.Graph) error {
	m, err := buildTPH(g)
	if err != nil || m == nil {
		return err
	}
	for _, p := range m.Patterns {
		if err := writeGo(
			filepath.Join(g.Target, "poly_tph_"+poly.Snake(p.Name)+".go"),
			[]byte(renderTPH(m, p)),
		); err != nil {
			return err
		}
		baseDir := filepath.Join(g.Target, p.Base.PackageDir())
		decls, err := exportedDecls(baseDir)
		if err != nil {
			return err
		}
		pdir := filepath.Join(g.Target, strings.ToLower(p.Name))
		if err := removeEntFiles(pdir); err != nil {
			return err
		}
		var b strings.Builder
		fmt.Fprintf(
			&b,
			"%spackage %s\n\nimport %q\n\n",
			header,
			strings.ToLower(p.Name),
			m.Package+"/"+p.Base.PackageDir(),
		)
		for _, d := range decls {
			if !p.mentionsVariant(d.name) {
				reexport(&b, p.Base.Package(), d.name, d.name, d.kind)
			}
		}
		if err := writeGo(filepath.Join(pdir, tphFile), []byte(b.String())); err != nil {
			return err
		}
		for _, v := range p.Members {
			vdir := filepath.Join(g.Target, strings.ToLower(v.Name))
			var vb strings.Builder
			fmt.Fprintf(
				&vb,
				"%spackage %s\n\nimport %q\n\n",
				header,
				strings.ToLower(v.Name),
				m.Package+"/"+p.Base.PackageDir(),
			)
			for _, d := range decls {
				for from, to := range v.Renames {
					if strings.Contains(d.name, from) {
						reexport(
							&vb,
							p.Base.Package(),
							d.name,
							strings.ReplaceAll(d.name, from, to),
							d.kind,
						)
					}
				}
			}
			if err := writeGo(filepath.Join(vdir, tphFile), []byte(vb.String())); err != nil {
				return err
			}
		}
	}
	var pb strings.Builder
	fmt.Fprintf(&pb, "%spackage predicate\n\n", header)
	for _, p := range m.Patterns {
		fmt.Fprintf(&pb, "type %s = %s\n", p.Name, p.BaseName())
	}
	if err := writeGo(
		filepath.Join(g.Target, "predicate", tphFile),
		[]byte(pb.String()),
	); err != nil {
		return err
	}
	return writeTPHEdges(g, m)
}

func writeTPHEdges(g *gen.Graph, m *tphModel) error {
	var b strings.Builder
	fmt.Fprintf(&b, "%spackage %s\n\n%s\n", header, pkgName(m.Package), polyMapSrc)
	b.WriteString("// PolyNode turns a TPH table's row from Noder into its variant; node and nodes resolvers return it.\nfunc PolyNode(n Noder) Noder {\n\tswitch b := n.(type) {\n")
	for _, p := range m.Patterns {
		fmt.Fprintf(&b, "\tcase *%s:\n\t\treturn %sOf(b)\n", p.BaseName(), lowerFirst(p.Name))
	}
	b.WriteString("\t}\n\treturn n\n}\n\n")
	byPkg := map[string][]*tphEdge{}
	for _, e := range m.Edges {
		renderEdge(&b, e)
		byPkg[e.T.PackageDir()] = append(byPkg[e.T.PackageDir()], e)
	}
	if err := writeGo(
		filepath.Join(g.Target, "poly_tph_edges.go"),
		[]byte(b.String()),
	); err != nil {
		return err
	}
	for dir, edges := range byPkg {
		decls, err := exportedDecls(filepath.Join(g.Target, dir))
		if err != nil {
			return err
		}
		var pb strings.Builder
		fmt.Fprintf(&pb, "%spackage %s\n\n", header, edges[0].T.Package())
		for _, e := range edges {
			from, to := e.Edge.StructField(), pascalOf(e.Name)
			for _, d := range decls {
				if strings.Contains(d.name, from) {
					reexport(&pb, "", d.name, strings.ReplaceAll(d.name, from, to), d.kind)
				}
			}
		}
		src := strings.ReplaceAll(pb.String(), " = .", " = ")
		if err := writeGo(
			filepath.Join(g.Target, dir, "poly_tph_edges.go"),
			[]byte(src),
		); err != nil {
			return err
		}
	}
	return nil
}

func pascalOf(s string) string { return gen.Funcs["pascal"].(func(string) string)(s) }

func renderEdge(b *strings.Builder, e *tphEdge) {
	T, N, E, P, B := e.T.Name, pascalOf(e.Name), e.Edge.StructField(), e.P.Name, e.P.BaseName()
	of := lowerFirst(P) + "Of"
	fmt.Fprintf(
		b,
		"func (n *%s) Query%s() *%sQuery { return &%sQuery{b: n.Query%s()} }\n\n",
		T,
		N,
		P,
		P,
		E,
	)
	fmt.Fprintf(
		b,
		"func (q *%sQuery) Query%s() *%sQuery { return &%sQuery{b: q.Query%s()} }\n\n",
		T,
		N,
		P,
		P,
		E,
	)
	fmt.Fprintf(
		b,
		"func (c *%sClient) Query%s(n *%s) *%sQuery { return &%sQuery{b: c.Query%s(n)} }\n\n",
		T,
		N,
		T,
		P,
		P,
		E,
	)
	fmt.Fprintf(b, `func (q *%[1]sQuery) With%[2]s(opts ...func(*%[3]sQuery)) *%[1]sQuery {
	return q.With%[4]s(func(bq *%[5]sQuery) {
		for _, o := range opts {
			o(&%[3]sQuery{b: bq, conv: %[6]s})
		}
	})
}

`, T, N, P, E, B, of)
	if !e.Many {
		fmt.Fprintf(b, `func (e %[1]sEdges) %[2]sOrErr() (%[3]s, error) {
	b, err := e.%[4]sOrErr()
	if err != nil {
		return nil, err
	}
	return %[5]s(b), nil
}

`, T, N, P, E, of)
		if e.GQL != nil {
			fmt.Fprintf(b, `func (n *%[1]s) %[2]s%[3]s (%[4]s, error) {
	b, err := n.%[5]s(%[6]s)
	if err != nil || b == nil {
		return nil, err
	}
	return %[7]s(b), nil
}

`, T, N, e.GQL.Params, P, E, e.GQL.Args, of)
		} else {
			fmt.Fprintf(b, `func (n *%[1]s) %[2]s(ctx context.Context) (%[3]s, error) {
	if b, err := n.Edges.%[4]sOrErr(); err == nil {
		return %[5]s(b), nil
	}
	b, err := n.Query%[4]s().Only(ctx)
	if err != nil {
		return nil, err
	}
	return %[5]s(b), nil
}

`, T, N, P, E, of)
		}
	} else {
		fmt.Fprintf(b, `func (e %[1]sEdges) %[2]sOrErr() ([]%[3]s, error) {
	bs, err := e.%[4]sOrErr()
	if err != nil {
		return nil, err
	}
	return polyMap(bs, %[5]s), nil
}

`, T, N, P, E, of)
		if e.GQL != nil {
			switch {
			case strings.Contains(e.GQL.Results, B+"Connection"):
				fmt.Fprintf(
					b,
					"func (n *%s) %s%s (*%sConnection, error) {\n\tc, err := n.%s(%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn poly%sConnectionOf(c), nil\n}\n\n",
					T,
					N,
					e.GQL.Params,
					P,
					E,
					e.GQL.Args,
					P,
				)
			default:
				fmt.Fprintf(
					b,
					"func (n *%s) %s%s ([]%s, error) {\n\tbs, err := n.%s(%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn polyMap(bs, %s), nil\n}\n\n",
					T,
					N,
					e.GQL.Params,
					P,
					E,
					e.GQL.Args,
					of,
				)
			}
		}
	}
	for _, recv := range []string{T + "Create", T + "UpdateOne", T + "Update"} {
		has := func(name string) bool { return e.Setters[recv+"."+name] }
		emit := func(name, sig, body string) {
			if !has(name) {
				fmt.Fprintf(b, "func (x *%s) %s%s *%s {\n\t%s\n}\n\n", recv, name, sig, recv, body)
			}
		}
		if !e.Many {
			setID := "Set" + E + "ID"
			if e.Field != "" {
				setID = "Set" + pascalOf(e.Field)
			}
			if has(setID) {
				emit("Set"+N, "(v "+P+")", "return x."+setID+"(v.GetID())")
				if setID != "Set"+N+"ID" {
					emit("Set"+N+"ID", "(id "+e.P.IDType+")", "return x."+setID+"(id)")
				}
			}
			if has("Clear" + E) {
				emit("Clear"+N, "()", "return x.Clear"+E+"()")
			}
			continue
		}
		singular := gen.Funcs["singular"].(func(string) string)
		baseIDs, ids := pascalOf(singular(e.Edge.Name))+"IDs", pascalOf(singular(e.Name))+"IDs"
		for _, op := range []string{"Add", "Remove"} {
			if has(op + baseIDs) {
				emit(op+ids, "(ids ..."+e.P.IDType+")", "return x."+op+baseIDs+"(ids...)")
				emit(op+N, "(vs ..."+P+")",
					"for _, v := range vs {\n\t\tx."+op+baseIDs+"(v.GetID())\n\t}\n\treturn x")
			}
		}
		if has("Clear" + E) {
			emit("Clear"+N, "()", "return x.Clear"+E+"()")
		}
	}
}

const polyMapSrc = `func polyMap[B any, T any](bs []B, f func(B) T) []T {
	out := make([]T, 0, len(bs))
	for _, b := range bs {
		out = append(out, f(b))
	}
	return out
}
`

func removeTPHOutput(target string) error {
	for _, glob := range []string{"poly_tph*.go", filepath.Join("*", tphFile), filepath.Join("*", "poly_tph_edges.go")} {
		stale, _ := filepath.Glob(filepath.Join(target, glob))
		for _, f := range stale {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
